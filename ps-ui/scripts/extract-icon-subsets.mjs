/**
 * Generates `src/lib/components/ui/icons/subsets.generated.ts` — slim Iconify
 * collections containing only the icons the app actually uses, scanned from
 * `src/`. Keeps the bundle small (full Tabler is ~2.9 MB, Phosphor ~2 MB)
 * while staying fully offline: no icon data is ever fetched at runtime.
 *
 * Besides the published packages, the `local` prefix is a local collection:
 * every `local:<name>` in source maps to `src/lib/components/ui/icons/local/<name>.svg`.
 * Drop an SVG there (fill/stroke on `currentColor` so the `color` prop works)
 * and reference it like any other icon.
 *
 * Run from ps-ui/ whenever icons are added or removed in source:
 *
 *   node scripts/extract-icon-subsets.mjs
 *
 * The generated file is committed, so builds and CI never regenerate it.
 * A new icon renders blank in dev until this script is re-run — that is the
 * deliberate tripwire that keeps the bundle honest.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const uiRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** prefix -> @iconify-json package. Keep in sync with iconCollections.ts. */
const COLLECTIONS = {
	tabler: '@iconify-json/tabler',
	ph: '@iconify-json/ph',
	'svg-spinners': '@iconify-json/svg-spinners',
	'line-md': '@iconify-json/line-md'
};

const LOCAL_PREFIX = 'local';
const LOCAL_DIR = join(uiRoot, 'src/lib/components/ui/icons', LOCAL_PREFIX);

const prefixes = [...Object.keys(COLLECTIONS), LOCAL_PREFIX];
const usagePattern = new RegExp(`\\b(${prefixes.join('|')}):([a-z0-9-]+)`, 'g');

// Scan source for used icon names per prefix.
const used = new Map(); // prefix -> Set<name>
const files = [];
(function walk(dir) {
	for (const entry of readdirSync(dir)) {
		const p = join(dir, entry);
		if (statSync(p).isDirectory()) walk(p);
		else if (/\.(svelte|ts)$/.test(entry)) files.push(p);
	}
})(join(uiRoot, 'src'));
for (const file of files) {
	const src = readFileSync(file, 'utf8');
	for (const match of src.matchAll(usagePattern)) {
		if (!used.has(match[1])) used.set(match[1], new Set());
		used.get(match[1]).add(match[2]);
	}
}

function fail(message) {
	console.error(message);
	process.exit(1);
}

function localIcon(name) {
	const path = join(LOCAL_DIR, `${name}.svg`);
	if (!existsSync(path)) fail(`Unknown ${LOCAL_PREFIX} icon: ${name} (expected ${path})`);
	const svg = readFileSync(path, 'utf8');
	const root = svg.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/);
	if (!root) fail(`${path}: not a single-root <svg> document`);
	const [, attrs, body] = root;
	const viewBox = attrs
		.match(/\bviewBox="([^"]+)"/)?.[1]
		.trim()
		.split(/[\s,]+/)
		.map(Number);
	if (!viewBox || viewBox.length !== 4 || viewBox.some(Number.isNaN)) {
		fail(`${path}: <svg> needs a numeric viewBox="minX minY width height"`);
	}
	const [left, top, width, height] = viewBox;
	const icon = { body: body.trim(), width, height };
	if (left) icon.left = left;
	if (top) icon.top = top;
	return icon;
}

// Build slim collections from the full JSON packages.
const subsets = [];
for (const [prefix, pkg] of Object.entries(COLLECTIONS)) {
	const names = used.get(prefix);
	if (!names || names.size === 0) continue;
	const full = JSON.parse(readFileSync(join(uiRoot, 'node_modules', pkg, 'icons.json'), 'utf8'));
	const icons = {};
	for (const name of names) {
		const icon = full.icons[name] ?? full.aliases?.[name];
		if (!icon) fail(`Unknown ${prefix} icon: ${name}`);
		icons[name] = icon;
	}
	// Root height/width carry the default viewBox; keep them per subset.
	const subset = { prefix, icons };
	if (full.height) subset.height = full.height;
	if (full.width) subset.width = full.width;
	subsets.push(subset);
	console.log(`${prefix}: ${names.size} icons`);
}

const localNames = used.get(LOCAL_PREFIX);
if (localNames && localNames.size > 0) {
	const icons = {};
	for (const name of localNames) icons[name] = localIcon(name);
	subsets.push({ prefix: LOCAL_PREFIX, icons });
	console.log(`${LOCAL_PREFIX}: ${localNames.size} icons`);
}

if (subsets.length === 0) {
	fail('No icons found in src/ — refusing to write an empty subset file.');
}

const file = `// Generated by scripts/extract-icon-subsets.mjs — do not edit by hand.
// Slim Iconify collections: only the icons used in src/, bundled for offline use.
import type { IconifyJSON } from '@iconify/types';
import { addCollection } from '@iconify/svelte/dist/offline-functions';

const iconSubsets: IconifyJSON[] = ${JSON.stringify(subsets, null, '\t')};

export function registerIconSubsets(): void {
	for (const subset of iconSubsets) {
		addCollection(subset);
	}
}
`;

writeFileSync(join(uiRoot, 'src/lib/components/ui/icons/subsets.generated.ts'), file);
console.log('Wrote subsets.generated.ts');
